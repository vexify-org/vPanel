//! 网站建站管理（对标宝塔「网站」模块）。
//!
//! 与 `nginx.rs`（反向代理站点）区别：这里管理的是**真实网站**——
//! 带站点根目录（docroot）、可选 PHP-FPM 映射、可选伪静态规则，可创建/删除/启停。
//!
//! 插桩设计：设置环境变量 `VPANEL_DRY_ROOT` 后，所有文件写入与 nginx 校验/reload
//! 都被重定向到 `$VPANEL_DRY_ROOT` 下，命令只会被记录而不真正执行，从而在未安装
//! Nginx 的环境里也能端到端验证控制逻辑（`cargo test` 即用此模式）。

use crate::json;

/// 是否启用 dry-run（插桩模式）。
fn dry() -> bool {
    !std::env::var("VPANEL_DRY_ROOT").unwrap_or_default().is_empty()
}

/// dry-run 模式下把绝对路径重定向到沙盒根下；否则原样返回。
fn dry_prefix(p: &str) -> String {
    match std::env::var("VPANEL_DRY_ROOT") {
        Ok(root) if !root.is_empty() => {
            let trimmed = p.trim_start_matches('/');
            format!("{}/{}", root.trim_end_matches('/'), trimmed)
        }
        _ => p.to_string(),
    }
}

/// nginx 配置根目录（与 nginx.rs 的 VIPanel 约定一致，可被 VPANEL_NGINX_DIR 覆盖）。
fn conf_dir() -> String {
    let base = std::env::var("VPANEL_NGINX_DIR").unwrap_or_else(|_| "/etc/nginx".to_string());
    dry_prefix(&base)
}

fn avail_dir() -> String {
    format!("{}/sites-available", conf_dir())
}
fn enabled_dir() -> String {
    format!("{}/sites-enabled", conf_dir())
}
fn conf_ext() -> &'static str {
    ".conf"
}

/// 网站根目录基础路径（可被 VPANEL_SITE_ROOT 覆盖）。
fn site_base() -> String {
    let base = std::env::var("VPANEL_SITE_ROOT").unwrap_or_else(|_| "/www/wwwroot".to_string());
    dry_prefix(&base)
}

/// 系统 PHP-FPM 默认 unix socket（可被 VPANEL_PHP_SOCKET 覆盖）。
fn php_socket() -> String {
    let s = std::env::var("VPANEL_PHP_SOCKET").unwrap_or_else(|_| "/run/php/php-fpm.sock".to_string());
    dry_prefix(&s)
}

fn available() -> bool {
    std::path::Path::new(&avail_dir()).is_dir()
}

/// 判断启用目录里是否存在指向该配置文件的（符号链接）启用项。
/// 用 symlink_metadata 避免跟随链接导致相对目标判空。
fn link_exists(enabled_dir: &str, fname: &str) -> bool {
    let lnk = std::path::Path::new(enabled_dir).join(fname);
    match std::fs::symlink_metadata(&lnk) {
        Ok(m) => m.file_type().is_symlink() || m.file_type().is_file(),
        Err(_) => false,
    }
}

/// 建立启用软链（用绝对目标，保证链接可解析）。
fn link_enable(name: &str, fname: &str) {
    let _ = std::fs::create_dir_all(enabled_dir());
    let avail = format!("{}/{}", avail_dir(), fname);
    let lnk = format!("{}/{}{}", enabled_dir(), name, conf_ext());
    let _ = std::process::Command::new("ln").args(["-s", &avail, &lnk]).status();
}

fn valid_name(n: &str) -> bool {
    !n.is_empty()
        && n.len() <= 64
        && n.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '.' | '_'))
}

fn valid_domain(d: &str) -> bool {
    let d = d.trim();
    !d.is_empty()
        && d.len() <= 253
        && !d.starts_with('-')
        && d.split('.').all(|label| {
            !label.is_empty()
                && label.len() <= 63
                && label.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
        })
}

/// 真实命令执行（dry-run 时打印到 stderr，模拟成功）。
fn run(cmd: &str) -> (bool, String) {
    if dry() {
        eprintln!("[vpanel:dryrun] {}", cmd);
        return (true, "(dry-run 已跳过)".into());
    }
    let out = std::process::Command::new("/bin/sh").arg("-c").arg(cmd).output();
    match out {
        Ok(o) => {
            let msg = {
                let s = String::from_utf8_lossy(&o.stdout);
                let e = String::from_utf8_lossy(&o.stderr);
                format!("{}{}", s, e).trim().to_string()
            };
            (o.status.success(), msg)
        }
        Err(e) => (false, e.to_string()),
    }
}

/// nginx 配置校验（dry-run 视为通过）。
fn nginx_test() -> (bool, String) {
    run("nginx -t 2>&1")
}

fn nginx_reload() -> (bool, String) {
    run("nginx -s reload 2>&1 || systemctl reload nginx 2>&1")
}

/// 确保目录存在（幂等）。
fn ensure_dir(p: &str) -> std::io::Result<()> {
    std::fs::create_dir_all(p)
}

