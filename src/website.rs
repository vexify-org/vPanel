fn parse_site(content: &str) -> (String, String, String, bool, bool) {
    // 返回 (listen, server_name, root, has_php, enabled)
    let mut listen = String::new();
    let mut server_name = String::new();
    let mut root = String::new();
    let mut has_php = false;
    let mut _enabled = true;
    for line in content.lines() {
        let t = line.trim();
        if let Some(v) = t.find("server_name") {
            if let Some(rest) = t.get(v + "server_name".len()..) {
                if server_name.is_empty() {
                    server_name = rest.split_whitespace().next().unwrap_or("").trim_end_matches(';').to_string();
                }
            }
        } else if t.find("root ").is_some() && !t.starts_with("try_files") {
            if let Some(rest) = t.get(t.find("root").unwrap() + "root".len()..) {
                if root.is_empty() {
                    root = rest.split_whitespace().next().unwrap_or("").trim_end_matches(';').to_string();
                }
            }
        } else if t.starts_with("listen") {
            if let Some(rest) = t.get("listen".len()..) {
                let first = rest.split_whitespace().next().unwrap_or("");
                if listen.is_empty() && !first.contains("ssl") {
                    listen = first.trim_end_matches(';').to_string();
                }
            }
        } else if t.contains("fastcgi_pass") {
            has_php = true;
        }
    }
    (listen, server_name, root, has_php, _enabled)
}

/// 站点列表 -> JSON。
pub fn website_list_json() -> String {
    if !available() {
        return format!("{{\"ok\":false,\"msg\":\"未找到 nginx 配置目录 {}\"}}", json::jesc(&avail_dir()));
    }
    let mut items = Vec::new();
    if let Ok(rd) = std::fs::read_dir(avail_dir()) {
        for ent in rd.flatten() {
            let fname = ent.file_name().to_string_lossy().into_owned();
            if !fname.ends_with(conf_ext()) {
                continue;
            }
            let name = fname.trim_end_matches(conf_ext()).to_string();
            let content = std::fs::read_to_string(ent.path()).unwrap_or_default();
            let (listen, server_name, root, has_php, _) = parse_site(&content);
            let is_website = !root.is_empty(); // 有 root 的才算“网站”（反代站 root 为空）
            if !is_website {
                continue;
            }
            let enabled = link_exists(&enabled_dir(), &fname);
            let docroot = root.clone();
            items.push(format!(
                "{{\"name\":\"{}\",\"domain\":\"{}\",\"listen\":\"{}\",\"root\":\"{}\",\"php\":{},\"enabled\":{}}}",
                json::jesc(&name),
                json::jesc(&server_name),
                json::jesc(&listen),
                json::jesc(&docroot),
                has_php,
                enabled,
            ));
        }
    }
    items.sort();
    format!(
        "{{\"ok\":true,\"basedir\":\"{}\",\"list\":[{}]}}",
        json::jesc(&avail_dir()),
        items.join(",")
    )
}

