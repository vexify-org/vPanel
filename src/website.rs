/// 生成一个纯静态网站的 server 块配置。
pub fn static_site_conf(domain: &str, port: &str, root: &str) -> String {
    format!(
        r#"# auto-generated by vPanel
server {{
    listen {port};
    server_name {domain};
    root {root};
    index index.html index.htm;

    location / {{
        try_files $uri $uri/ =404;
    }}

    access_log /var/log/nginx/{domain}.access.log;
}}
"#,
        port = port,
        domain = domain,
        root = root,
    )
}

/// 生成一个接入 PHP-FPM 的站点配置。
pub fn php_site_conf(domain: &str, port: &str, root: &str, socket: &str) -> String {
    format!(
        r#"# auto-generated by vPanel
server {{
    listen {port};
    server_name {domain};
    root {root};
    index index.php index.html index.htm;

    location / {{
        try_files $uri $uri/ /index.php?$query_string;
    }}

    location ~ \.php$ {{
        include fastcgi_params;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_pass unix:{socket};
    }}

    access_log /var/log/nginx/{domain}.access.log;
}}
"#,
        port = port,
        domain = domain,
        socket = socket,
        root = root,
    )
}

/// 常用伪静态规则生成（对标宝塔内置模板）。
pub fn rewrite_block(kind: &str) -> String {
    match kind {
        "wordpress" | "wp" => r#"location / {
    if (-f $request_filename) { break; }
    if (-e $request_filename) { break; }
    rewrite ^(.+)$ /index.php?q=$1 last;
}
"#
        .into(),
        "thinkphp" => "location / {\n    if (!-e $request_filename) {\n        rewrite ^/(.*)$ /index.php/$1 last;\n    }\n}\n"
            .into(),
        "laravel" => r#"location / {
    try_files $uri $uri/ /index.php?$query_string;
}
"#
        .into(),
        "none" => String::new(),
        _ => String::new(),
    }
}

